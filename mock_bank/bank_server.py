def _в_диапазоне(платеж: dict, дата_с: str, дата_по: str) -> bool:
    """Попадает ли платёж в запрошенный период. Пустые границы не ограничивают."""
    дата = платеж["doc_date"]
    if дата_с and дата < дата_с:
        return False
    if дата_по and дата > дата_по:
        return False
    return True


@app.route("/api/v1/statement", methods=["GET"])
def получить_выписку():
    """Выписка за период — основной метод, который дёргает 1С.

    Сбои имитируются намеренно, чтобы обработка в 1С училась их переживать:
    без ретраев и Попытка...Исключение она будет падать примерно на каждом пятом
    запуске регламентного задания.
    """
    if random.random() < ВЕРОЯТНОСТЬ_СБОЯ:
        вид_сбоя = random.choice(["500", "таймаут"])
        if вид_сбоя == "500":
            print("  ! Имитирую сбой: 500 Internal Server Error")
            return jsonify({"error": "Internal server error"}), 500
        print("  ! Имитирую сбой: долгий ответ (35 сек)")
        time.sleep(35)  # больше типового таймаута — обработка должна его поймать

    дата_с = request.args.get("date_from", "")
    дата_по = request.args.get("date_to", "")
    платежи = [п for п in ВЫПИСКА if _в_диапазоне(п, дата_с, дата_по)]

    print(f"  → Отдал выписку: {len(платежи)} платежей за {дата_с or '...'} — {дата_по or '...'}")

    return jsonify({
        "account": НАШ_СЧЕТ,
        "organization": НАША_ОРГАНИЗАЦИЯ,
        "date_from": дата_с,
        "date_to": дата_по,
        "count": len(платежи),
        "payments": платежи,
    })


@app.route("/api/v1/balance", methods=["GET"])
def получить_остаток():
    """Остаток на счёте. Пригодится для сверки после загрузки выписки."""
    поступило = sum(п["amount"] for п in ВЫПИСКА if п["direction"] == "IN")
    списано = sum(п["amount"] for п in ВЫПИСКА if п["direction"] == "OUT")
    return jsonify({
        "account": НАШ_СЧЕТ,
        "balance": round(поступило - списано, 2),
        "currency": "RUB",
        "updated_at": datetime.now().isoformat(timespec="seconds"),
    })


