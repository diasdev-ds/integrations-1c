"""
МОК БАНКА — имитирует API банка для интеграции с 1С.

Зачем: разрабатывать интеграцию «Банк → 1С» без реального договора с банком.
Код обработки в 1С, написанный против этого мока, потом работает с боевым API —
меняется только адрес и авторизация.

ИНН вместо БИН. Учебная Бухгалтерия — российская, у контрагентов реквизит ИНН.
Поэтому выписка сделана под неё: ИНН и рубли. У казахстанского клиента будет
БИН и тенге, но логика сопоставления абсолютно та же — ищем контрагента
по налоговому идентификатору. Меняется только имя реквизита в запросе.

ИНН взяты РЕАЛЬНЫЕ, из демо-базы «Бухгалтерия предприятия учебная (демо)».
Поэтому сопоставление даёт живой результат, а не пустоту.

ВАЖНО: выписка отдаётся НАМЕРЕННО «грязной». Это не баг, а суть тренажёра.
Настоящие банковские выписки именно такие, и вся ценность интеграции —
в умении их разобрать. Что подмешано специально:

  * ИНН в назначении платежа пишется по-разному: «ИНН 7799745640»,
    «инн7799731397», «ИНН: 612200076042» — ловить регулярным выражением
  * ИНН бывает 10-значный (у ООО) и 12-значный (у ИП) — регулярка обязана
    ловить оба, иначе платежи от ИП будут молча теряться
  * у одного платежа ИНН в назначении вообще нет, только в реквизитах
  * два плательщика отсутствуют в справочнике 1С — обработка не должна падать
  * платёж 000000123 приходит ДВАЖДЫ — проверка идемпотентности
  * «Клик ООО» и «Клик-Сервис ООО» — похожие названия, разные ИНН.
    Сопоставлять по названию нельзя, только по ИНН
  * сервер в 20% случаев отвечает 500 или зависает — проверка ретраев

Запуск:  python bank_server.py
Проверка: http://127.0.0.1:8080/api/v1/statement?date_from=2026-07-01&date_to=2026-07-31
"""

